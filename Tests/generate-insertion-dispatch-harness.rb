#!/usr/bin/env ruby

# Copies the production dispatch/focus methods into the test-only state shim.
# The substitutions below replace only macOS process/Accessibility entry points
# with synthetic adapters; the method control flow stays sourced from AppState.

abort "usage: ruby #{File.basename($PROGRAM_NAME)} Sources/AppState.swift output.swift" unless ARGV.length == 2

source_path, output_path = ARGV
source = File.read(source_path)
lines = source.lines

method_names = %w[
  prepareForegroundApplicationForInsertion
  insertTranscriptWhenShortcutReleased
  performAtTarget
  sameAccessibilityElement
  pressEnterAfterPaste
  pressEnterAtTarget
  userInputEventCounts
]

methods = method_names.map do |name|
  matches = lines.each_index.select do |index|
    lines[index].match?(/^\s*(?:private\s+)?(?:static\s+)?func #{Regexp.escape(name)}\b/)
  end
  abort "expected exactly one #{name} method in #{source_path}, found #{matches.length}" unless matches.length == 1

  start = matches.first
  finish = ((start + 1)...lines.length).find { |index| lines[index] == "    }\n" }
  abort "could not find four-space method terminator for #{name} in #{source_path}" unless finish
  lines[start..finish].join
end

api_substitutions = {
  "AXIsProcessTrusted()" => "TestAX.isProcessTrusted",
  "NSRunningApplication(processIdentifier:" => "TestAX.runningApplication(processIdentifier:",
  "NSWorkspace.shared.frontmostApplication" => "TestAX.frontmostApplication",
  "AXUIElementCreateApplication" => "TestAX.applicationElement",
  "AXUIElementPerformAction" => "TestAX.performAction",
  "AXUIElementSetAttributeValue" => "TestAX.setAttributeValue",
  "CFEqual" => "TestAX.elementsEqual",
  "kAXFocusedWindowAttribute as CFString" => "TestAX.focusedWindowAttribute",
  "kAXFocusedUIElementAttribute as CFString" => "TestAX.focusedElementAttribute",
  "kAXFocusedAttribute as CFString" => "TestAX.focusedAttribute",
  "kAXRaiseAction as CFString" => "TestAX.raiseAction",
  "kCFBooleanTrue" => "true",
  "app.activate(options: [.activateIgnoringOtherApps])" => "app.activate()",
  "CGEventSource.counterForEventType(" => "TestAX.counterForEventType(",
  "AXUIElement?" => "TestAXElement?"
}

generated_methods = methods.map do |method|
  api_substitutions.each { |from, to| method = method.gsub(from, to) }
  method
end

generated = <<~SWIFT
  // Generated by Tests/generate-insertion-dispatch-harness.rb from Sources/AppState.swift.
  import AppKit
  import ApplicationServices
  import CoreGraphics
  import Foundation

  extension TestInsertionState {
      typealias AppTextInsertionTarget = TestInsertionTarget
      typealias PendingClipboardRestore = TestPendingClipboardRestore
      typealias DispatchQueue = TestDispatchQueue

  #{generated_methods.join("\n")}

      func testPrepareForegroundApplicationForInsertion() {
          prepareForegroundApplicationForInsertion()
      }

      func testDispatchInsertion(
          _ transcript: String, target: TestInsertionTarget?, shouldPressEnter: Bool, useOriginalField: Bool
      ) {
          insertTranscriptWhenShortcutReleased(
              transcript, target: target, shouldPressEnter: shouldPressEnter, useOriginalField: useOriginalField
          )
      }

      func testPerformAtTarget(
          _ target: TestInsertionTarget, action: @escaping () -> Bool, completion: @escaping (Bool) -> Void
      ) {
          performAtTarget(target, action: action, completion: completion)
      }

      func testScheduleEnterAfterPaste(
          target: TestInsertionTarget?, completion: (() -> Void)? = nil
      ) {
          pressEnterAfterPaste(target: target, completion: completion)
      }
  }
SWIFT

File.write(output_path, generated)
